 *
 * **为什么要单独一份**：原来狼的提示词只写了「伪装成好人、盘身份、别投队友」，
 * 模型收敛出的唯一主动作就是悍跳预言家——每局都一样，好人两局就看穿了。
 * 打法放在这里、由头狼每局临场挑一套，同一套板子能打出不同的局。
