package com.feature.werewolf.prompt.rules

import com.feature.werewolf.game.WerewolfConfig
import com.feature.werewolf.game.WerewolfRole
import com.feature.werewolf.game.WinRule

/**
 * 全局限定：胜负、绑票、投票流程、遗言、自爆。
 *
 * 和 `prompt/roles` 的分工：这里写的是**所有人共用**的规则（谁能赢、平票怎么办），
 * 身份规则（守卫怎么守、狼王怎么开枪）挂在身份上。混在一起写过一次，代价是
 * 改守卫规则时要在一千行里找到唯一那条 `if`。
 *
 * 「绑票」和「平票怎么处理」必须写进去：这两条决定了白天的算术——
 * 好人投错一次就再也追不回来，狼人可以故意把票打成平手。不写，
 * 模型就会按「平票还有一轮 PK」的线下记忆去推，推出的结论整个是错的。
 *
 * 同理，有警长和没警长的板子必须给出**不同的**平票规则：警长在场上才能追加一轮，
 * 而且 1.5 票会让「谁跟谁投」变得比人数更重要。
 */
internal fun rulesBrief(config: WerewolfConfig): String {
    val win = when (config.winRule) {
        WinRule.SLAY_SIDE -> buildString {
            append("【胜负规则】屠边局：狼人杀光所有神职，或杀光所有平民，狼人获胜；")
            append("好人放逐全部狼人则好人获胜。屠边之前先过绑票这一关。\n")
            // 「神职」这两个字模型会按网上的记忆理解成「预言家 + 女巫 + 猎人」，
            // 而本局的神职还包括守卫、白痴、熊。不把名单钉死，狼就会按错的目标数
            // 算进度（刀完预女猎以为自己屠神了），白天也判不清场上还剩几张神。
            val gods = WerewolfRole.entries.filter { it.isGod && config.has(it) }
            if (gods.isEmpty()) {
                append("本局**没有神职**：屠边只有平民这一条边，杀光所有平民狼人就赢。\n")
            } else {
                append("本局算神的是：").append(gods.joinToString("、") { it.displayName })
                append("——这几张**全部出局**才算屠神。白痴被票翻牌不算出局，翻牌之后再死才算；")
                append("狼人（含狼王）永远不算神，除神职以外的好人都是平民。\n")
            }
            // 「或」在中文里极易被读成「两条都行、随便打」。实测狼会今晚压神边、
            // 明晚又去砍民，最后一算两边都差一刀，一个屠边都没打成。
            // 这是胜利条件本身的后果，不是打法偏好，所以写进规则里。
            if (gods.isNotEmpty() && config.has(WerewolfRole.VILLAGER)) {
                append("**两条边必须选一条打穿**：神边和民边分着刀，最常见的结局是")
                append("两边都差最后一刀，谁也没屠成。\n")
            }
        }

        WinRule.SLAY_ALL ->
            "【胜负规则】屠城局：狼人票权不少于好人票权时狼人获胜（警长一票算 1.5 票）；" +
                "好人放逐全部狼人则好人获胜。"
    }
    return buildString {
        append(win).append("\n")
        // 绑票比的是**票权**不是人头：警长那 1.5 票也要算进去。
        // 写成「人数」的话，模型会按人头推，警长在手时推出来的结论整个是错的。
        append("【绑票】狼人票权不少于好人票权时，狼人直接获胜，游戏当场结束——")
        append("这时所有人一起投也压不过狼队的票，投不出人了。\n")
        append(mutualProtectionBrief(config))
        if (config.hasSheriff) {
            // 退水是竞选流程的一半，不写进来的话模型只会「上警 → 发言 → 投票」，
            // 少一整步，而且退水的人该不该被投票、还有没有票，全是规则后果。
            append("【竞选与退水】天亮先上警，想当的人各说一段，说完之后有一次**退水**——")
            append("候选人可以放弃竞选。退水的人不再被投票，首轮也没有警长票（上过警的人首轮不投）；")
            append("所有候选人都退水，本局就没有警长；只剩一个人不退，他直接当选。")
            // 首轮没票 ≠ 整场没票：PK 轮的投票权按「台上台下」分，不看有没有上过警。
            append("如果警下投出平票，平票的人 PK 之后重投——那一轮台上的人不能投，")
            append("**台外所有活着的人都能投，退水的人也算**。\n")
            append("【白天投票】平票时，平票的人再各说一轮（PK），然后由全体重投一次；")
            append("再平票就当天无人出局。警长的一票算 1.5 票。\n")
            // 警长选方向是每天一次的公开动作：规则要说给所有人听，
            // 否则警长选了死左，其他玩家会以为发言顺序乱了。
            // 「左 / 右」在线上没有真正的左右手，必须钉死成座位号方向，不然每个人理解都不同。
            append("【发言顺序】每天讨论开始前，警长在四个方向里选一个（左 = 座位号增大的方向，")
            append("右 = 座位号减小的方向）：**警左 / 警右**从警长自己的左手边 / 右手边起，")
            append("绕一圈，警长最后一个发言（归票位）；**死左 / 死右**从昨夜死者的左手边 / ")
            append("右手边起（多人倒牌按座位号最小的那个算），这时警长不一定是最后一个。")
            append("平安夜没人倒牌，就只有警左 / 警右两个选项。")
            // 警长缺席的日子不只出现在「没选出来」的板子上：竞选被自爆炸掉、
            // 警长死了没交接，都会落到同一条。不写清楚，模型会以为发言顺序乱了。
            append("警长不在场时（还在顺延、双爆作废、出局没交接），起点和方向**由系统随机指定**。\n")
        } else {
            append("【白天投票】本局没有警长，没有 PK：平票就是当天无人出局，不存在加投一轮。\n")
            // 没有警长就没人主持，起点与方向只能由系统随机指定。
            // 原来写的是「从昨夜死者下位起」，那是固定位置先开口，先说话的人优势明显。
            append("【发言顺序】本局没有警长，没人主持：每天的**起点和方向都由系统随机指定**，" +
                "可能从任何一个人开始，也可能倒着绕。\n")
        }
        append("【遗言】第一夜出局的人、每次被投票放逐的人、以及任何原因出局的警长，")
        append("出局后都会留一段遗言；第二夜起，夜里死的人不再发言。")
        // 两件事必须分开写：遗言是「能不能说话」，警徽移交是「警长一死就得处理的那个动作」。
        // 混成一条，模型会以为被枪带走的警长「连徽一起没了」，或者反过来给自己补一段遗言。
        append("**被猎人开枪带走的人不留遗言**，当场出局，不能再说任何话；")
        append("但他如果是警长，**警徽这一刻照样要处理**——交给一个存活玩家，或者撕掉。\n")
        append(darkCardBrief(config))
        append("【自爆】狼人可以在白天发言时自爆：当场出局，这一天立刻结束——没有投票、")
        append("没有人被放逐，直接进入黑夜。**在竞选发言里自爆**时竞选中止，警徽不作废，")
        append("**顺延到下一个白天重新竞选**：这一天没人当选，警徽还挂着，下一个天亮接着选。")
        // 「单爆吞白天，双爆吞警徽」：不写清楚，狼会以为一次自爆就把警徽炸没了，
        // 好人也会在第二天看到「又上警」时以为引擎出错。
        append("连续两次竞选都被自爆打断（双爆）才算吞掉警徽：那之后本局不再有警长。")
        // 警上每一段发言都算「一次打断」，PK 发言不算例外——不点明的话，
        // 狼会把 PK 当成「已经投过票了，爆一下没关系」。
        append("只要还在警上流程里（竞选发言、平票 PK 发言都算），爆一次就记一次，不分阶段。")
        // 本局独有的收尾：不让它写清楚，狼会以为自己爆完就连夜话也没了。
        append("自爆的狼**当晚仍在狼队里**：照常参加夜里商议和定刀，定刀结束后才离场；")
        append("**出局是永久的**：除了当晚那一次商议，这一局他不会再上场——")
        append("不再发言，也不能投票或开枪。\n")
        append("【夜里】狼人多数决，平票加商一次。刀可以落在任何人身上——包括狼自己人，")
        append("也可以主动空刀。")
    }
}

/**
 * 守救同归规则：守卫守的人同时被女巫救，仍然会死。
 *
 * **两种模式都要给。** 这不是打法教学，是本局的硬规则事实——而且只在守卫+女巫
 * 同时在场时成立，模型无法从「标准局先验」推出来。更麻烦的是守卫自己的 notes
 * 里写着「你守的人当夜不会被刀死」：不补这条，守救同归发生时守卫会以为自己
 * 守晚了、女巫会以为救的人被狼补刀，好人全场据此推错。
 *
 * 自由模式曾把 `rulesBrief` 和 `boardBrief` 整段砍掉，连 `GuardKit.rules` 一起
 * 砍没了（守卫 notes 里没有这条），于是这条规则在自由模式彻底消失。抽成独立
 * 函数，两种模式共用同一份文案。
 */
internal fun mutualProtectionBrief(config: WerewolfConfig): String =
    if (config.has(WerewolfRole.GUARD) && config.has(WerewolfRole.WITCH)) {
        "【守救同归】守卫守的人如果同时被女巫救了，他**还是会死**：" +
            "两种保护叠在一起反而同归于尽。守卫和女巫都只知道自己做的那一半，" +
            "所以你守的人、你救的人有可能已经被对方「也做了一次」。\n"
    } else {
        ""
    }

/**
 * 暗牌局规则：出局不公开底牌。
 *
 * **两种模式都要给。** 这条不是打法教学，是本局的硬规则事实——它决定
 * 「出局能不能作为推理依据」。模型对「标准局放逐翻牌」的先验太强，
 * 不给就会编出「某人放逐翻出好人」，全场跟着一句谣言走，局就被假信息带偏
 * （真局：3 号女巫被查杀票出，第二天全员采信不存在的翻牌）。
 *
 * 自由模式曾把 `rulesBrief` 整段砍掉，连这条一起砍了，于是老 bug 复发。
 * 抽成独立函数，两种模式共用同一份文案，不再各自维护。
 */
internal fun darkCardBrief(config: WerewolfConfig): String = buildString {
    append("【底牌】本局是**暗牌局**：任何人出局都不公开底牌，夜里死亡、被放逐、")
    append("被枪带走全都一样。系统不会播报死者的身份，你也看不见别人的牌。")
    if (config.has(WerewolfRole.IDIOT)) {
        append("唯一的例外是白痴：被票到时翻牌亮明身份，但不出局。\n")
    } else {
        append("本局没有白痴，不存在任何翻牌环节。\n")
    }
    append("**谁在发言里说「某人翻出好人 / 翻出狼」，都只是他自己的说法，不是事实**——")
    append("除非有预言家的查验背书，否则不要采信，更不要把它当成推理的立足点。\n")
}

/**
 * 狼人杀通用术语表。
 *
 * 模型按训练里的「标准局先验」说话，但网上的叫法五花八门，同一个词各人理解不同，
 * 它就会自己造词或把词用反——比如把「警徽流」说成「验人链」、把「抗推」说成「抗票」、
 * 或者冒出「隐狼」「狼链」这类本局根本没有的概念。术语一旦乱，全场推理就雞同鸭讲。
 *
 * 两种风格都给：术语是**语言约定**，不是打法。自由式不给方法，但没理由允许瞎编词。
 * 只列本 App 实际会用到的说法，附带极简释义帮它用对，不做打法教学。
 */
internal fun terminologyBrief(): String = buildString {
    append("【术语约定】只用下面这些通用说法，不要自造黑话，也不要用本局不存在的概念：\n")
    append("预言家验人：验出的好人叫**金水**，验出的狼叫**查杀**。\n")
    append("**跳身份 / 报身份**＝公开声称自己是某个身份；狼人冒充预言家叫**悍跳**，")
    append("两人同时自称同一身份叫**对跳**（谁真谁假自己判断）。\n")
    append("**警徽流**＝预言家报出的「我接下来准备验谁」的验人顺序，")
    append("用来给好人留后手；不要说成「验人链」「验人顺序表」等别的名字。\n")
    append("**站边**＝相信并支持某一边（某个预言家）；狼人假装站在好人一边叫**倒钩**，")
    append("狼人公开帮队友冲锋叫**冲锋**。\n")
    append("**归票**＝发言末位（常由警长）总结当日票型、带大家投某人的动作；")
    append("**抗推**＝设法把票推到自己怀疑的人身上。\n")
    append("**平安夜**＝夜里没有人出局；**定刀**＝狼队商量确定当晚刀谁（可以空刀）。\n")
    append("**绑票**＝狼人票权压过好人直接赢；警长一票算 1.5 票。\n")
    append("**预女猎守**＝预言家、女巫、猎人、守卫四种常见神职的合称，")
    append("说本局身份时用具体名字，不要生造「某种狼」「某某侠」这类不存在的身份。\n")
    append("拿不准某个词是不是通用说法时，直接用大白话说清楚意思，不要硬套术语。")
}
