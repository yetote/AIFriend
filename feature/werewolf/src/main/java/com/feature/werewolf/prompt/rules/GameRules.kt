package com.feature.werewolf.prompt.rules

import com.feature.werewolf.game.WerewolfConfig
import com.feature.werewolf.game.WerewolfRole
import com.feature.werewolf.game.WinRule

/**
 * 全局限定：胜负、绑票、投票流程、遗言、自爆。
 *
 * 和 `prompt/roles` 的分工：这里写的是**所有人共用**的规则（谁能赢、平票怎么办），
 * 身份规则（守卫怎么守、狼王怎么开枪）挂在身份上。混在一起写过一次，代价是
 * 改守卫规则时要在一千行里找到唯一那条 `if`。
 *
 * 「绑票」和「平票怎么处理」必须写进去：这两条决定了白天的算术——
 * 好人投错一次就再也追不回来，狼人可以故意把票打成平手。不写，
 * 模型就会按「平票还有一轮 PK」的线下记忆去推，推出的结论整个是错的。
 *
 * 同理，有警长和没警长的板子必须给出**不同的**平票规则：警长在场上才能追加一轮，
 * 而且 1.5 票会让「谁跟谁投」变得比人数更重要。
 */
internal fun rulesBrief(config: WerewolfConfig): String {
    val win = when (config.winRule) {
        WinRule.SLAY_SIDE ->
            "【胜负规则】屠边局：狼人杀光所有神职，或杀光所有平民，狼人获胜；好人放逐全部狼人则好人获胜。" +
                "屠边之前先过绑票这一关。"

        WinRule.SLAY_ALL ->
            "【胜负规则】屠城局：狼人票权不少于好人票权时狼人获胜（警长一票算 1.5 票）；" +
                "好人放逐全部狼人则好人获胜。"
    }
    return buildString {
        append(win).append("\n")
        // 绑票比的是**票权**不是人头：警长那 1.5 票也要算进去。
        // 写成「人数」的话，模型会按人头推，警长在手时推出来的结论整个是错的。
        append("【绑票】狼人票权不少于好人票权时，狼人直接获胜，游戏当场结束——")
        append("这时所有人一起投也压不过狼队的票，投不出人了。\n")
        if (config.has(WerewolfRole.GUARD) && config.has(WerewolfRole.WITCH)) {
            // 这条必须写给**所有人**：守卫和女巫互相不知道对方做了什么，
            // 守救同归时牌桌上看起来就是「明明守了又救了，怎么还是死了」。
            // 不提前说明，女巫会以为自己救的人被狼补刀，守卫会以为是自己守晚了。
            append("【守救同归】守卫守的人如果同时被女巫救了，他**还是会死**：")
            append("两种保护叠在一起反而同归于尽。守卫和女巫都只知道自己做的那一半，")
            append("所以你守的人、你救的人有可能已经被对方「也做了一次」。\n")
        }
        if (config.hasSheriff) {
            append("【白天投票】平票时，平票的人再各说一轮（PK），然后由全体重投一次；")
            append("再平票就当天无人出局。警长的一票算 1.5 票。\n")
            // 警长选方向是每天一次的公开动作：规则要说给所有人听，
            // 否则警长选了逆序，其他玩家会以为发言顺序乱了。
            append("【发言顺序】每天讨论开始前由警长选一次方向：顺时针（从警长下一位起）")
            append("或逆时针（从警长上一位倒着绕）。警长自己永远最后发言（归票位）。")
        } else {
            append("【白天投票】本局没有警长，没有 PK：平票就是当天无人出局，不存在加投一轮。\n")
            append("【发言顺序】每天从昨夜死者的下一位开始，按座位号绕一圈。\n")
        }
        append("【遗言】第一夜出局的人、每次被投票放逐的人、以及任何原因出局的警长，")
        append("出局后都会留一段遗言；第二夜起，夜里死的人不再发言。")
        // 两件事必须分开写：遗言是「能不能说话」，警徽移交是「警长一死就得处理的那个动作」。
        // 混成一条，模型会以为被枪带走的警长「连徽一起没了」，或者反过来给自己补一段遗言。
        append("**被猎人开枪带走的人不留遗言**，当场出局，不能再说任何话；")
        append("但他如果是警长，**警徽这一刻照样要处理**——交给一个存活玩家，或者撕掉。\n")
        // 这条必须明说：模型对「标准局放逐翻牌」的先验太强，不写就会编出
        // 「某人放逐翻出好人」——全场跟着一句谣言走，局就被假信息带偏了
        // （真局：3 号女巫被查杀票出，第二天全员采信不存在的翻牌）。
        // 引擎只在白痴被票时翻牌，其他一切死亡都不公开身份。
        append("【底牌】本局是**暗牌局**：任何人出局都不公开底牌，夜里死亡、被放逐、")
        append("被枪带走全都一样。系统不会播报死者的身份，你也看不见别人的牌。")
        if (config.has(WerewolfRole.IDIOT)) {
            append("唯一的例外是白痴：被票到时翻牌亮明身份，但不出局。\n")
        } else {
            append("本局没有白痴，不存在任何翻牌环节。\n")
        }
        append("**谁在发言里说「某人翻出好人 / 翻出狼」，都只是他自己的说法，不是事实**——")
        append("除非有预言家的查验背书，否则不要采信，更不要把它当成推理的立足点。\n")
        append("【自爆】狼人可以在白天发言时自爆：当场出局，这一天立刻结束——没有投票、")
        append("没有人被放逐，直接进入黑夜。**在竞选发言里自爆**时选举当场中止，")
        append("本局按「无人上警」处理，没有警长。这条规则对狼是最后手段，不是常规打法。\n")
        append("【夜里】狼人多数决，平票加商一次。刀可以落在任何人身上——包括狼自己人，")
        append("也可以主动空刀。")
    }
}
