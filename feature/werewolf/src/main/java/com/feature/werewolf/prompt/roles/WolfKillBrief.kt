package com.feature.werewolf.prompt.roles

import com.feature.werewolf.game.WerewolfGame
import com.feature.werewolf.game.WerewolfRole

/**
 * 狼队夜里该怎么算这一刀——**按本局板子来**。
 *
 * 说明「刀被守住就无效」只是规则，狼真正缺的是**怎么用这条规则**：守卫不能连守同一人，
 * 所以昨夜没死的刀口今晚是裸的，该补刀而不是换人；反过来，刚跳出来的预言家正是
 * 守卫第一顺位要守的人，硬刀大概率撞守。实测缺这一段时，狼第二夜照旧闷头刀预言家，
 * 撞了守还以为只是运气差。
 *
 * 板子里**没有守卫**时也不能沉默：狼会拿着「平安夜=有人守住了」的老经验去猜一个
 * 本局根本不存在的身份，把女巫的解药漏算掉。
 *
 * 只喂**公开可得**的信息：昨夜刀了谁（狼自己定的）、那个人天亮后有没有出局（播报里人人听得到）、
 * 本局有没有守卫（板子是公开的）。**绝不读 `NightRecord.guarded`**——守卫守了谁是他的
 * 私有信息，写进狼的提示词等于把守人路线直接交出去，一局就毁了。
 */
internal object WolfKillBrief {

    fun of(game: WerewolfGame): List<String> {
        // 用 `deaths` 而不是「现在还在不在存活名单里」：后者会把白天被票出的人也当成
        // 「这一刀砍死了」，狼就会误判守卫那晚守的是别人。
        val record = game.nights.lastOrNull { it.day == game.day - 1 }
        val target = record?.wolfTarget
        val killed = target != null && target in record.deaths

        // 每条都**不带**「· 」前缀：privateBriefing 会统一加，自己再加一遍会变成「· ·」。
        if (!game.config.has(WerewolfRole.GUARD)) {
            val lines = mutableListOf<String>()
            if (game.config.has(WerewolfRole.WITCH)) {
                lines += "【本局没有守卫】没有任何人能挡住你们的刀。平安夜只可能是女巫用了解药，" +
                    "或者你们自己那一夜空刀。"
                lines += "如果是女巫救的，那瓶解药已经空了——今晚刀谁都不会再被救第二次。"
                if (target != null && !killed) {
                    lines += "昨夜刀 $target 号没落地，就是上面这两种情况之一。今晚再刀他，没人挡得住。"
                }
            } else {
                lines += "【本局没有守卫也没有女巫】没有任何技能能挡住你们的刀，平安夜只可能是你们自己空刀。"
            }
            return lines
        }

        val lines = mutableListOf<String>()
        lines += "【和守卫博弈】本局有守卫，下刀之前先把这一层算进去："
        lines += "刀落在被守住的人身上，这一刀**完全无效**：没有死讯，天亮就是平安夜。" +
            "不是「打残」，是这一夜白过。"
        lines += "守卫只有一条硬限制：**不能连续两夜守同一个人**——他昨夜守了谁，今晚就一定守不了谁。" +
            "这是他对你们唯一露出来的破绽。"

        if (target == null) {
            // 第一夜（或上一夜空刀）没有刀口可算，硬套「昨夜怎么怎么样」只会让模型编事实。
            lines += "还没有可用的刀口记录（本局第一夜，或上一夜空刀）。"
            lines += "第一夜守卫也没有任何信息，多半守自己、或者猜一个最像神职的位——这一刀撞守只能认；" +
                "「他昨夜守过谁」要等第二夜起才有的算。"
            return lines
        }

        if (!killed) {
            lines += "昨夜你们刀的是 $target 号，他**还活着**——那一刀被守或被救挡住了。" +
                "别纠结是哪一种：守卫守的，他今晚不能再守；女巫救的，解药只有一瓶、已经用掉了。" +
                "两种情况下**今晚连刀 $target 号都是最稳的一刀**，别因为「刚被他躲过去」就换目标。"
        } else {
            lines += "昨夜你们刀的是 $target 号，他**出局了**：这一夜没能被救下来。" +
                "守卫的守人路线你们仍然看不到——但他今晚会去守「最该守、又还没守过」的位：" +
                "刚跳出来的预言家，或者他自己。"
        }

        lines += "别把「刀预言家」当成默认选项：他正是守卫第一顺位要守的人。" +
            "昨夜刚守过的位置、以及明显已经被保护起来的位置，今晚再刀就是撞守，白白空一夜。"
        lines += "想稳拿一个人头就刀**外置位**：发言少、没什么身份味道、守卫不会为他花一次守护的人。" +
            "空一刀什么都换不到，稳一刀至少让好人白天少一张票。"
        lines += "该硬刀的情况只有一种：昨夜刀口就是预言家而他**还活着**——他今晚裸着，这刀必须补，" +
            "别再换人；换人等于让他再报一天验人。"
        return lines
    }
}
