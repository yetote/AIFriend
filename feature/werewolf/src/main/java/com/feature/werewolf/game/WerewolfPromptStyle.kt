package com.feature.werewolf.game

/**
 * 提示词的两种风格。
 *
 * [GUIDED] 是现状：除了身份和局势，还给模型一整套「怎么判断、怎么打」的方法——
 * 读人框架、身份作业、狼队战术菜单、屠边账。小模型靠它才不至于说废话，
 * 但对强推理模型来说这些方法可能是拐杖，甚至把它带偏。
 *
 * [FREE] 是给强模型的实验档：只给身份、规则、局势、私有信息和本轮任务，
 * **不给任何打法**——怎么读人、怎么发言、狼队怎么配合，全由模型自己判断。
 * 注意「不给打法」不等于「不给底线」：保密约束、信息隔离、输出格式照旧，
 * 否则模型会在白天说出「我昨晚验了 3 号」，那已经不是自由发挥，是破坏游戏。
 *
 * 存的是枚举名而不是布尔值：以后想加第三档（比如只要读人框架、不要战术菜单）
 * 不用改存档格式。设置层按 name 读写，UI 侧同名枚举由 route 映射。
 */
enum class WerewolfPromptStyle {
    /** 内置打法全开。默认，保证老用户和已有存档行为不变。 */
    GUIDED,

    /** 只给事实与底线，打法交给模型自己想。 */
    FREE,
}
