package com.feature.werewolf.game

/**
 * 提示词的三种风格。
 *
 * [GUIDED] 是默认：除了身份和局势，还给模型一整套「怎么判断、怎么打」的方法——
 * 读人框架、身份作业、狼队战术菜单、屠边账。小模型靠它才不至于说废话，
 * 但对强推理模型来说这些方法可能是拐杖，甚至把它带偏。
 *
 * [FREE] 是给强模型的实验档：只给身份、规则、局势、私有信息和本轮任务，
 * **不给打法倾向**——怎么发言、怎么藏、狼队怎么配合，全由模型自己判断。
 * 但**可核对的事实判据照给**（翻牌硬反证、验人改口、警徽流兑现、放逐轮次、票型对账）——
 * 那是「怎么核对局面」的硬事实，不是答案；实测把整套打法砍光的版本会把编造的心路当真、
 * 忽略翻牌这种硬反证，那不是「自由」，是让它瞎打。
 * 注意「不给打法」不等于「不给底线」：保密约束、信息隔离、输出格式照旧，
 * 否则模型会在白天说出「我昨晚验了 3 号」，那已经不是自由发挥，是破坏游戏。
 *
 * [SEARCH] 更彻底：**连规则细节都不给**，只交代版型（几狼几神几民）和胜负条件，
 * 同时允许模型联网检索——规则、身份技能、常见打法都让它自己查。
 * 这是对「模型本来就知道狼人杀」这个假设的直接下注：查得明白，提示词就能短到
 * 只剩本局的非标准设定；查不明白，它会比 [FREE] 更差——所以它是实验档，不是默认。
 *
 * 三档共有的底线（一档都不能少）：身份与私有事实、本轮任务与输出格式、保密约束。
 * 拿掉这些不是「自由」，是让它没法打完这一局——不知道自己是谁、不知道要输出什么。
 *
 * 存的是枚举名而不是布尔值：以后想加第四档不用改存档格式。
 * 设置层按 name 读写，UI 侧同名枚举由 route 映射。
 */
enum class WerewolfPromptStyle {
    /** 内置打法全开。默认，保证老用户和已有存档行为不变。 */
    GUIDED,

    /** 只给事实与底线，打法交给模型自己想。 */
    FREE,

    /** 只给版型与胜负，其余交给模型的既有知识与联网检索。 */
    SEARCH,
}
