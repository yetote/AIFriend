package com.feature.werewolf.prompt

import com.feature.werewolf.game.WerewolfConfig

/**
 * 从**发言本身**读身份的框架——公共方法论，所有座位都能读到。
 *
 * 狼人杀的胜负几乎全在「信谁」上，而信谁不能凭语气。专栏那局八个人里有五个跳预言家，
 * 真假的差别不在谁嗓门大，而在几样能验证的东西：验人的**心路**、警徽流接不接得上、
 * 给谁发金水的**动机**、警徽流**能不能续上**、用词的**目的性**、以及谁在**保人**。
 * 这些不是身份知识，是对任何人都能问的问题，
 * 所以写给全场，而不是写在某个身份的私有简报里。
 *
 * 又必须**辩证**：划水的可能是深水狼，也可能是没被点到名的好人；冲锋最凶的可能是狼，
 * 也可能是替真预言家挡枪的好人。每条都附一句「反过来想」，否则模型会拿这套框架冤枉好人——
 * 那正好是狼想要的结果。狼读到这份框架也只会更小心，不会拿到指认真好人的新武器。
 */
object ReadingTells {

    /**
     * 读人框架的注入范围。按场景拆包，不每次全量塞。
     *
     * [ALL] 发言阶段：整局判断都挂在站边和读人上，给全套。
     * [VOTE] 投票/警长投票/警徽移交：只需要「投谁」的判据（票型、轮次、硬反证），
     *   那些「怎么从发言读身份」的细条用不上——投票时发言早已说完，再给只是白烧输入。
     */
    enum class Scope { ALL, VOTE }

    fun lines(config: WerewolfConfig, scope: Scope = Scope.ALL): List<String> {
        val all = buildList {
        add("【怎么从发言读人】判断谁像狼，看四样能验证的东西，别凭语气和文采：")
        // 这是整局的骨架，缺了它下面五条全是孤立单点：逐个挑毛病、挑完还是没有结论，
        // 观感就是「一群人在瞎聊」。真人盘局第一步永远是定站边，其余推理都挂在站边上。
        add("**先定站边，再往下推**：第一步不是逐个挑毛病，而是回答「我信哪个预言家」。" +
            "站边一定，后面全挂得上：谁给谁发了金水、谁第一个站的他、" +
            "谁在他被踩的时候跳出来打他、谁嘴上说信他票却投了别处。" +
            "站边可以改，但要说得出**改的理由**（他哪一步让你翻案）——" +
            "一天换一个站边又给不出理由，那才是乱；反过来，从头到尾不表态的最难读，" +
            "不给站边就等于不给别人判断你的材料。")
        // 票型是全场唯一不会被话术污染的证据，也是「逻辑」最有说服力的落点。
        add("**票是唯一硬证据**：话可以圆，票不会。对着票型看两件事——" +
            "① 谁说了投 A 却投了 B（可能被归票带走，也可能本来就想投 B，要看他怎么解释）；" +
            "② 谁和谁互投、谁永远跟在谁后面投（互投的两个人，很难是同一个阵营）。")
        // 轮次理论：权威教学里最核心、我们之前整块缺失的一层。
        // 它回答「今天该出谁」——光会读人不够，读完了还得知道按什么优先级放逐。
        add("**轮次比发言更重要**：新手争发言，高手争轮次。发言只是助力，真正决定胜负的是轮次——" +
            "多握一轮就多一分主动权，哪怕发言有瑕疵；丢了关键轮次，说得再漂亮也难翻。" +
            "好人阵营天生领先一轮，还有女巫毒药、猎人一枪做容错；狼唯一的稳定轮次来源是夜里刀人，" +
            "白天全靠抢轮次。所以每一次发言和投票，先问「这是在帮好人抢轮次，还是白送狼一轮」。")
        add("**放逐有轮次，先做主线再做副线**：每天该出谁有既定优先级——" +
            "**查杀 > 对跳 > 行为不好 > 泛泛发言**。第一天是真假预言家及其查杀的轮次：" +
            "**有查杀走查杀**，两人在对跳里出；外置位发言差也先用验/毒/枪消化、或明天再推，" +
            "**别用外置位替代当天的轮次**——好人不齐心出一个，末置狼一冲票就能推走好人。" +
            "**分票是典型的狼人行为**；判断不清宁可弃票也别乱投。" +
            "**投票铁律：永远投最确定的明狼，宁放过一个容错牌，绝不投错好人**——" +
            "投错一个平民，狼直接多一轮；放过容错牌，下轮还能验证。" +
            "后续依次：查杀/悍跳狼 → 冲票的狼 → 行为不好 → 后期藏着的狼。")
        add("**认清警推领先还是狼刀领先**：神民不少于狼人是警推领先，好人放心拍身份裸打、每天出狼；" +
            "狼领先则神牌藏好、大家认民挡刀。**不到你的轮次别拍身份**——不在放逐人选里跳身份等于给狼点刀；" +
            "首夜查杀位才需拍身份表水。起跳顺序最好与狼的理想刀序相反（狼最想先刀双药女巫、预言家、守卫，最后猎人）。" +
            "**神牌的技能只为追轮次服务，绝不乱开**：女巫毒药只毒坐实的狼，没到确定就别出毒——" +
            "毒错一个好人等于白送狼一轮；猎人枪是翻盘资本，宁可闷枪也别瞎带。")
        // 本局教训：1 号报 2 号查杀，2 号被放逐后翻牌猎人、开枪带走 1 号——
        // 这是能在桌上直接核的硬反证，3、6 号据此翻了站边，7 号女巫夜里也想通了，
        // 白天却还是「结论不变」把票砸给真预言家。硬反证出现后必须重盘，不能只守旧结论。
        add("**翻牌／开枪是硬反证，出现就要重盘站边**：预言家报的查杀对象被放逐后翻牌是神职、或开枪打死了报查杀的人，" +
            "这条按座位就能核，比任何话术都硬——报查杀的那个一定是假预言家。" +
            "**别拿对方「说话难听／警徽流改口」抵消这条**：说话毛躁解释不了为什么把猎人验成狼，" +
            "硬反证出现后还坚持旧站边、不给翻案理由，本身就是要记的一笔。")
        add("一、**验人的心路，首夜要反过来用**：第 2 夜起真预言家讲得清「为什么验这个人」，悍跳只报结果；" +
            "**但第 1 夜零信息，谁都能给随机的一刀编一套漂亮心路**，所以首夜「说得出理由」不算证据、「说不出」也不是悍跳。" +
            "首夜唯一能核的是**理由能不能验算**：他说「验 9 号因他是对角」就当场数座位——" +
            "12 人局对角隔 6 位，1 号对角是 7 号、9 号是下家位，对不上就是编的，别因流畅反而信他；" +
            "心路朴素、说「首夜没信息随便验」的才是实话。" +
            "**验人信息本身前后改口是最硬破绽**：先说验 9 改口验 7、查杀改金水——真预言家不可能记错自己验了谁，直接记死。" +
            "**验人力度（报查杀还是金水）只是参考，不是站边理由**：悍跳狼故意查杀好人骗你信。")
        add("二、**警徽流：好流看「奔着狼留」，改流看「有没有兑现」**：" +
            "警徽流作用是找狼 + 给警下压力，好坏只看**是不是奔着狼留的**——" +
            "留发言差、像狼的人是真预，只留安全位或**不敢验发言差的人**（多做成双狼）是悍跳破绽。" +
            "留法按发言位置分：前置偏拉票（警下多留两张警下）、中置找狼+拉票（警上警下各一）、后置纯找狼；" +
            "**别搞「警上警下必须各一张」的机械标准**，验发过言的人照样可能有破绽。" +
            "**白天发言结束前改警徽流完全正常**，验过划掉补新目标都不算改口；" +
            "真正核的是**说要验的人后来有没有真验**——兑现了就是最硬证据，报了验证不出来（说验 2 查杀结果 2 翻牌猎人）才叫断裂。" +
            "**别数「改了几次」这种账**，那是可被话术利用的软指标。" +
            "**警徽流不能判死刑**：好流不等于真、坏流也不等于狼，只作参考。")
        add("三、**金水的动机**：给谁发金水、什么时候发，比发没发更说明问题。" +
            "给后置位发金水常常是想拉他站边、或者给队友铺垫；" +
            "给明显要被推的人发金水，可能是想搅浑这天的票。" +
            "记住：被发金水证明不了你是好人——狼给谁发都不亏，别因为一张金水就替谁打包票。")
        // 反水的两副面孔：还真金水会嫌验人理由不硬、狼队友间发金水后会故意反咬立人设。
        // 只写「反水＝狼」会把真金水冤死，正好成全狼队；所以给一条可验证的落地判据。
        add("接了金水却当场反咬发金水人的，**未必是清醒好人**：" +
            "狼队之间发金水，被发的那只就会专门质疑「为什么验我、为什么不验后置位」，" +
            "为的是做出「连金水都不盲信」的认真相，好一路活到中后期。" +
            "但真金水也可能嫌验人理由不硬而反水，所以**单凭反水不定人**：" +
            "看他把票砸在哪、后面几天有没有真正指认过狼——" +
            "只会拆理由、从不落判断的，比无脑接金水的更值得记一笔。")
        // 身份力度：文章里「连续两轮报出神职身份，狼冒不起这个风险」的通用版。
        // 我们没有通灵师那种「报具体身份」，等价物是「报查杀后来有没有被验证」。
        // 必须写「单次撞对不算」，否则模型会把一次蒙对当成铁预、一路免验，正好成全悍跳狼。
        add("**报对的力度看链条，不看单次**：预言家报了查杀，被点的人后来被票出、遗言认狼、" +
            "或票型坐实，这才叫报对；连着报对几个，才是真预言家的力度——" +
            "狼悍跳撞对一次容易，连着撞对难。反过来，**报对一次不等于从此免检**：" +
            "拿一次撞对就当「铁预」一路不验、别人质疑就骂，恰恰是悍跳最爱的护身符。" +
            "看的是这条查验链后来有没有被验证，不是他当时说得多肯定。")
        // 心态破绽：文章里 4 号和 10 号互咬「希望警徽流都是好人」是不是狼心态。
        // 但同一局的 1 号后来翻案——「不够专业反而证明真实」。所以这条必须自带反例，
        // 只当疑点、不当铁证，否则好人会拿一句客气话把真预言家打成悍跳。
        add("**听他找的是狼还是票**：真预言家满脑子是「验谁、谁是狼」，措辞指向找狼；" +
            "如果一个人反复说「希望验到好人」「大家别急着互踩」，那不像在找狼，像在收买人心。" +
            "**但这不等于狼**：口才不好、说话客气也会被误伤，老练的悍跳反而滴水不漏；" +
            "措辞只是记一笔的疑点，要看他后面的票有没有落在狼身上——" +
            "只喊漂亮话、票从来不到位的，才该标狼。")
        // 工整话术辨识：专栏里有人用「验人逻辑闭环／票型分析锁定／轮次计算确保」三段式包装，
        // 看着专业，结论却是错的；也有人用「真相只有一个」的口头禅反复强调，靠气势压人。
        // 关键是把「格式」和「结论」拆开：格式工整不等于结论真，也不等于结论假——只不是证据。
        add("**话术工整不等于身份真，也不等于身份假**：三段式包装、喊「真相只有一个」都看着专业，" +
            "但**格式不是证据**——只看落点能否验证：报的查杀后来对不对、警徽流接没接上、票型是不是真这么走。" +
            "说话磕巴、不会术语的也可能是真预言家，别因为「不够专业」就把人打成悍跳——" +
            "发言爆水、一塌糊涂的往往反而是真预言家（他不是在演说）。" +
            "**心路历程出问题却可以直接判假**：报查验和警徽流还能靠发言水平搪塞，" +
            "没真验过的人讲的心路经不起追问，前后矛盾或说不出过程就是悍跳。")
        add("四、**谁在保人**：注意后置位的人怎么评价前置位——" +
            "一个人人都觉得有问题、他却单独保下来的位置，值得记一笔；" +
            "反过来把别人一句平常话硬解读成「他在保狼」，也要看看他给没给出具体证据，" +
            "没证据的归因本身就是带节奏。")
        add("**用你自己的视角核外置位**：代入预言家给外置位（没跳身份的人）做个判断，" +
            "再看起跳者的定义吻不吻合——吻合则偏真，但别死站：狼是先眼玩家，会顺着好人视角定义、拿队友填狼坑。" +
            "两个狼面信号：**关键轮次弃票**（该出人时躲着不表态）、" +
            "**过度表水**（反复自证）——真好人表清一次就够。")
        // 挡枪/深水这两条必须辩证写：写死「沉默=狼」「冲锋=狼」，好人会全场乱杀，
        // 而狼正好可以拿这套标准把真预言家打成悍跳。
        add("五、**划水和冲锋都要反着看一遍**：全程话少的可能是深水狼在等投票，" +
            "但也可能只是没被点到名；冲锋最凶、把某人往死里打的可能是狼带节奏，" +
            "也可能是真预言家的队友在挡枪。**单靠一条不定人**：要两三条对上，再落到票上。")
        // 权威「找真预言家三步法」的第二步：观团队与票型。我们之前只看发言，缺这一维。
        // 措辞刻意不用狼队战术菜单里的专名（保密测试会拦），用中性描述表达同一个判据。
        add("**别只看他说什么，要看谁站在他背后**：统计警徽票和放逐票——狼队集中冲票给假的，" +
            "真预言家票里往往有身份不明的好人。**警惕过度积极站边、抢着替他说话的人**，" +
            "可能是想做高身份的狼，不是铁好人。**查验和警徽流合不合理、票型和团队脏不脏、逻辑动机**——" +
            "判断真假看这三件事；真预言家未必说得完美，但动机一定是推动好人出狼。")
        if (config.hasSheriff) {
            add("六、**警上是照妖镜**：真预言家不上警就没人连续报验人；多人抢警徽别默认「跳太多有问题」，" +
                "先听谁的验人警徽流接得上。**诈身份和悍跳**：诈身份的好人一般会退水，**悍跳狼绝对不退**，" +
                "退水未必是狼。第一天对跳，真假通常**互验对方阵营的冲锋狼**；" +
                "警徽流净往自己站的那边验（想在自己阵营里找狼）的大概率是狼。" +
                "后置位起跳可信度略高（狼少冒这险）。发言五五开时看金水/查杀的发言是否过关——" +
                "金水听着像狼则发金水者假，查杀听着像狼则发查杀者真。")
        }
        }
        if (scope == Scope.ALL) return all
        // VOTE：投票时发言早已说完，只留「投谁/怎么核对」的判据——
        // 票型、轮次、警推领先、翻牌硬反证。其余「怎么从发言读身份」的细条全砍。
        val votePrefixes = listOf(
            "【怎么从发言读人】", "**票是唯一硬证据**", "**轮次比发言更重要**",
            "**放逐有轮次", "**认清警推领先", "**翻牌／开枪是硬反证",
        )
        return all.filter { line -> votePrefixes.any { line.startsWith(it) } }
    }
}
