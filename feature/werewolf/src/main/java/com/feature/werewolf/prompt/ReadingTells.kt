package com.feature.werewolf.prompt

import com.feature.werewolf.game.WerewolfConfig
import com.feature.werewolf.game.WerewolfRole

/**
 * 公共推理准则（v2 重构版）。
 *
 * 彻底抛弃旧版 2300 字互相打架的补丁式长文，改成**6 条互不矛盾、可直接核验的硬准则**，
 * 并按阶段场景精确裁剪：
 * - [Scope.ALL]：白天讨论 / 完整推理；
 * - [Scope.SHERIFF]：上警 / 竞选发言 / 退水 / 警长投票（只给警上核心判据，大幅减噪）；
 * - [Scope.VOTE]：白天投票 / 遗言 / 开枪（由 `WerewolfPrompt.factsBrief` 提供精简核对表）。
 */
object ReadingTells {

    enum class Scope { ALL, SHERIFF, VOTE }

    fun lines(config: WerewolfConfig, scope: Scope = Scope.ALL): List<String> = when (scope) {
        Scope.VOTE -> emptyList()
        Scope.SHERIFF -> sheriffLines(config)
        Scope.ALL -> dayLines(config)
    }

    /** 警上专属准则：聚焦「首夜零信息」「谁该争警徽」「警长票≠有查杀必投查杀」。 */
    private fun sheriffLines(config: WerewolfConfig): List<String> = buildList {
        add("【警上推理准则】")
        add("1. **首夜零信息，不拿心路判假**：第 1 夜没有任何发言，预言家只报 1 个验人、验到死人、或如实说「随机/按位置验」全都正常；首夜唯一可核的是理由能否验算（如 12 人局 1 号对角是 7 号）。别把「编不出心路」或「准备根据发言改警徽流」当成悍跳破绽。")
        add("2. **谁该争警徽与退水**：警徽主要由真预言家争夺。非预言家好人（平民、女巫、守卫、猎人）**绝不冒充「真预言家」报假金水死占警徽**；若上警诈身份（只给后置位上警发查杀施压），听完预言家起跳后应**主动退水**，别赖在台上搅乱警徽。悍跳狼通常不退水。")
        add("3. **警长票看真假，不盲投查杀**：警长票投给你综合判断最像真预言家的人——**「有查杀走查杀」只管白天放逐顺序，绝不等于警长票必须投给报查杀的人**（悍跳狼最爱发查杀骗警徽）。重点看金水反水关系、发言漏洞与警徽流是否奔着找狼留。")
    }

    /** 白天完整推理准则：精简、辩证、零内部矛盾。 */
    private fun dayLines(config: WerewolfConfig): List<String> = buildList {
        add("【白天推理准则】看可核对的事实，不凭语气、嗓门或工整话术定身份：")
        add("1. **核硬账（最高优先级）**：真预言家不会记错自己验了谁，**验人对象或结论前后改口（如第 1 天报金水、第 2 天打铁狼）基本坐实假预**；发言说投 A 实际投 B、或反复前后双标，都是可当场核对的硬疑点。")
        add("2. **首夜与次夜分开看**：第 1 天零信息，只报 1 个验人、验到死人、说不出心路全正常（只核座位等可验算事实）；第 2 天起看验人动机和**警徽流有没有兑现**（白天发言结束前改流、验过划掉补新目标都合法，别数「改了几次」）。")
        add(
            buildString {
                append("3. **暗牌与特殊事件的边界**：暗牌局出局不翻牌，**猎人开枪只代表猎人个人怀疑，不等于「验出对方是狼」**。")
                if (config.has(WerewolfRole.IDIOT)) {
                    append("若被查杀者翻牌白痴，则报查杀者铁假，必须立刻重盘站边。")
                }
                if (config.has(WerewolfRole.WITCH)) {
                    append("**双死夜必是一刀一毒**：若警长或跳预者死在双死夜，必须同时盘「真预吃刀」和「悍跳狼吃毒」两种可能，接了他移交的警徽绝不等于他必是真预言家。")
                }
            }
        )
        add("4. **金水、反水与团队票型**：狼给谁发金水都不亏，被发金水证明不了干净；接金水反咬既可能是真预反水立警或真金水不满，也可能是狼队演戏反咬，看他后续票落哪。别只听台词，更要看谁站在他背后——谁警徽票与放逐票全程绑定冲票、谁过度积极护场；划水和冲锋都要反着想一遍，单靠一条不定人。")
        add("5. **放逐轮次与残局票权**：白天放逐优先级为 **查杀 > 对跳 > 行为与票型破绽**。第 1 天有查杀优先在查杀位与报查杀者间解决（防狼查杀狼），不要随意拿外置位替代主轮次，避免无理由分票；但「跟着多数/警长归票」本身不是狼证。存活人少时必须先算狼坑与票权，投错好人可能立刻被绑票输掉。")
        add("6. **身份与起跳纪律**：非预言家好人绝不冒充真预抢警徽；神职平时少裸拍防点刀，但**双药用完的女巫、面临被抗推或真预被冤的神职，必须果断跳明身份并报出完整信息（银水/毒口/守护记录）**，绝不藏到出局或害队友猎人开错枪。")
        if (config.hasSheriff) {
            add("7. **警长票与放逐分开**：回看警下票型时牢记「给查杀狼投警徽票」可能是好人误判轮次，也可能是狼队冲票，要结合白天发言和后续投票交叉验证。")
        }
    }
}
