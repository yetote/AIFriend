package com.feature.werewolf.game

/**
 * 局面阶段。
 *
 * 这里只保留**有规则后果**的阶段：夜晚每一个阶段各自需要不同的行动者，白天投票需要计票。
 * 「白天讨论」没有规则后果（说话不改变任何状态），但它是编排层调度发言的锚点，所以保留。
 *
 * 刻意没有 DAWN 阶段：天亮结算（谁死了、猎人能不能开枪）是一次性同步完成的，
 * 中间态对外不可见，多一个阶段只会让编排层多一次无意义的等待。
 *
 * 夜晚的顺序是**守卫 → 狼人 → 预言家 → 女巫**，不是随手排的：守卫必须在狼人之前，
 * 否则他就能看着刀口去守（见 [WerewolfRole.GUARD]）；女巫必须在狼人之后，因为她要被告知刀口。
 */
enum class Phase(val displayName: String) {
    /** 守卫选择今晚守谁。先于狼人，守卫不知道刀口。 */
    NIGHT_GUARD("守卫守护"),

    /** 狼人选择今晚要刀的人。存活狼人全部投票，多数决。 */
    NIGHT_WOLF("狼人行动"),

    /** 预言家查验。 */
    NIGHT_SEER("预言家查验"),

    /** 女巫决定是否用解药 / 毒药，每次行动结束后立即结算天亮。 */
    NIGHT_WITCH("女巫用药"),

    /** 白天讨论。规则上不做任何判定，由编排层按座位顺序驱动发言。 */
    DAY_DISCUSSION("白天讨论"),

    /** 白天投票。 */
    DAY_VOTE("白天投票"),

    /** 等待猎人开枪（或不开）。 */
    HUNTER_SHOOT("猎人开枪"),

    /** 分出胜负，游戏结束。 */
    FINISHED("游戏结束"),
}
