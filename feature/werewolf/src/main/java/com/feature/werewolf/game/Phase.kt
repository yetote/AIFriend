package com.feature.werewolf.game

/**
 * 局面阶段。
 *
 * 这里只保留**有规则后果**的阶段：夜晚每一个阶段各自需要不同的行动者，白天投票需要计票。
 * 「白天讨论」没有规则后果（说话不改变任何状态），但它是编排层调度发言的锚点，所以保留。
 *
 * 刻意没有 DAWN 阶段：天亮结算（谁死了、猎人能不能开枪）是一次性同步完成的，
 * 中间态对外不可见，多一个阶段只会让编排层多一次无意义的等待。
 *
 * 夜晚的顺序是**守卫 → 狼人 → 预言家 → 女巫**，不是随手排的：守卫必须在狼人之前，
 * 否则他就能看着刀口去守（见 [WerewolfRole.GUARD]）；女巫必须在狼人之后，因为她要被告知刀口。
 */
enum class Phase(val displayName: String) {
    /** 守卫选择今晚守谁。先于狼人，守卫不知道刀口。 */
    NIGHT_GUARD("守卫守护"),

    /**
     * 狼人内部商议。按座位顺序发言，只有狼人看得到。
     *
     * 单独成一个阶段，是因为「先说清楚再动手」本来就是两步：商议时人人可以改主意，
     * 下刀时各人定下自己的选择。并成一步的话，每只狼只能并发地丢一个目标，
     * 谁也听不到别人在说什么，各砍各的就是必然结果——第一夜最容易演变成空刀。
     */
    NIGHT_WOLF_CHAT("狼人商议"),

    /** 狼人各自定下今晚刀谁。存活狼人全部表态，多数决。 */
    NIGHT_WOLF("狼人下刀"),

    /** 预言家查验。 */
    NIGHT_SEER("预言家查验"),

    /** 女巫决定是否用解药 / 毒药，每次行动结束后立即结算天亮。 */
    NIGHT_WITCH("女巫用药"),

    /**
     * 夜间汇聚节点：守卫 / 狼人 / 预言家三路并发，都完成后才进女巫。
     *
     * 各路完成状态看 transcript 里有没有该身份当夜的发言——续档时发言已落库，
     * 就不会再跑这一路。详见 [com.feature.werewolf.engine.WerewolfChain]。
     */
    NIGHT_PENDING("夜间进行中"),

    /**
     * 天亮结算节点：所有夜间行动都只写状态，死亡、守救同归、胜负、猎人开枪、天亮播报
     * 统一在这一步结算一次。这样守卫 / 狼人 / 预言家 / 女巫可以并发，不必各自结算
     * 导致读不到别人同时写入的结果。
     */
    DAWN_SETTLE("天亮结算"),

    /**
     * 上警：每人表态要不要竞选警长。
     *
     * 只在「开了警长」的板子上出现：第 1 天，以及竞选被自爆打断之后的顺延日。
     * **先于死讯遗言**：线下流程是天亮先竞选，
     * 竞选结束之后夜里死的人才留遗言——这段顺序影响很大，先遗言的话，
     * 死者的遗言会直接左右投票，等于给死人一张选票。
     */
    DAY_SHERIFF_SIGNUP("警长竞选"),

    /** 候选人依次发表竞选发言。平票 PK 时也回到这个阶段，只是候选人收窄了。 */
    DAY_SHERIFF_SPEECH("竞选发言"),

    /**
     * 退水：竞选发言说完之后，候选人可以放弃竞选。
     *
     * 只在第一轮出现。平票 PK 之后再退水等于让投票白投，规则上不这么做——
     * 那一轮 [DAY_SHERIFF_SPEECH] 结束直接进投票。
     */
    DAY_SHERIFF_WITHDRAW("退水"),

    /** 警下投票选警长。上过警的人首轮不投票；平票 PK 那轮台上不投、台外都能投。 */
    DAY_SHERIFF_VOTE("警长投票"),

    /** 白天讨论。规则上不做任何判定，由编排层按发言顺序驱动发言。 */
    DAY_DISCUSSION("白天讨论"),

    /** 白天投票。 */
    DAY_VOTE("白天投票"),

    /**
     * 遗言。规则上同样不做判定，只是给「刚出局的人」一个说话的位置。
     *
     * 它必须有独立的阶段，而不是塞进 [DAY_DISCUSSION]：
     * 白天讨论的发言顺序是「活人从某人下位起」，遗言是**死者**说话，
     * 混在一起的话，牌桌上会出现一个已经出局的人插在活人中间发言，
     * 而且遗言结束后要么投票、要么入夜，下一步完全不同。
     */
    DAY_LAST_WORDS("遗言"),

    /**
     * 等待开枪（或不开）。猎人和狼王共用这个相位——两者被票出 / 被刀时的结算顺序完全一样，
     * 只是公开播报里的称呼不同。
     */
    HUNTER_SHOOT("开枪"),

    /** 分出胜负，游戏结束。 */
    FINISHED("游戏结束"),
}
