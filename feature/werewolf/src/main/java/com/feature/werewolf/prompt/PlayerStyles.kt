/**
 * 牌桌上的「打牌风格画像」——这是**角色设定**，不是打法教学。
 *
 * 和陪伴人设的分工：陪伴人设（`Friend.prompt`）写这个人平时怎么说话（猫娘、傲娇、
 * 元气）；风格画像写这个人**在牌桌上是个什么样的牌手**——做什么决定、信什么证据、
 * 遇到压力怎么反应。两者叠在一起，才既有「听得出是谁」又有「想得不重样」。
 *
 * 为什么单独做一份：陪伴人设全是闲聊/拟人向，天然把模型带向「表演语气」；
 * 实测一局里 AI 把脑力花在口头禅上，「他想/故意/骗」这类读到对手的发言几乎没有。
 * 风格画像补的正是这一层——给它一个**博弈的性格**，让它把注意力从「我是猫娘」
 * 挪到「我是个多疑的人，我要去看他为什么突然保人」。
 *
 * 红线（和自由模式不诱导的原则一致）：
 * - 只写「你是谁、你习惯怎么想」，不写「悍跳/倒钩/冲锋、第几天该干嘛」这类战术教学；
 * - 不写身份判断的结论（不说「跳预的多半是狼」），那会冤枉好人；
 * - 不给私有信息、不改保密底线——它影响的只是**思考的气质和读人的角度**。
 *
 * 因为只是角色设定，两种提示词风格（引导/自由）都拼这段：
