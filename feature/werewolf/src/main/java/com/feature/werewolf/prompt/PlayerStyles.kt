/**
 * 把选中好友稳定地分到不同风格：同桌尽量不重样，才有「几种打法碰一桌」的效果。
 *
 * 纯函数、不依赖 Android：
 * - 同一个 [friendId] 永远分到同一个风格（续档、复盘重算都不变）；
 * - 人数不超过风格数时，靠「哈希 + 占用回避」保证尽量不重复；
 * - 超过风格数时循环使用，重复无可避免，但至少分布均匀。
 *
 * [pinned] 是用户手动指定的映射（friendId → styleId），优先于自动分配。
 */
internal fun assignPlayerStyles(
    friendIds: List<String>,
    pinned: Map<String, String> = emptyMap(),
): Map<String, PlayerStyle> {
    if (friendIds.isEmpty()) return emptyMap()
    val all = PlayerStyle.entries
    val result = LinkedHashMap<String, PlayerStyle>()
    val used = HashSet<String>()
    // 先安置手动指定的，自动分配要避开它们
    for (id in friendIds) {
        val style = pinned[id]?.let { PlayerStyle.fromId(it) }
        if (style != null) {
            result[id] = style
            used.add(style.id)
        }
    }
    val auto = friendIds.filter { it !in result }
    for (id in auto) {
        val start = abs(stableHash(id)) % all.size
        var pick = all[start]
        for (offset in 1..all.size) {
            val candidate = all[(start + offset) % all.size]
            if (candidate.id !in used) { pick = candidate; break }
        }
        result[id] = pick
        used.add(pick.id)
    }
    return friendIds.associateWith { result.getValue(it) }
}

/** 不依赖 Kotlin hashCode（跨进程可能带随机化），自己写一个稳定的字符串哈希。 */
private fun stableHash(s: String): Int {
    var h = 0
    for (ch in s) h = 31 * h + ch.code
    return h
}

/**
 * 把风格画像拼进 system prompt。
 *
 * 放在陪伴人设**之后**：先说这个人平时什么语气，再说他在牌桌上是什么牌手，
 * 最后一句点明谁优先——实测不点明的话，模型会把风格当成「又一段人设」，
 * 继续去演语气而不是调整判断方式。
 *
 * [config] 留作日后按板子微调（比如无警长的板子不该出现「警徽流」字样）；
 * 目前所有板子共用同一份画像，参数先占住，避免以后改签名动一圈调用方。
 */
internal fun playerStyleBrief(style: PlayerStyle?, config: WerewolfConfig): String? {
    if (style == null) return null
    val body = if (config.hasSheriff) {
        style.brief.trim()
    } else {
        style.brief.trim().replace("警徽流接不接得上", "验人逻辑接不接得上")
    }
    return buildString {
        append("【你在牌桌上的性格】\n")
        append(body)
        append("\n\n")
        append("这不是你平时的说话人设，而是你打这局牌时的思考方式。" +
            "它决定你**信什么、疑谁、怎么下判断**，优先于上面那段日常性格；" +
            "但你仍然受身份、阵营和保密底线约束——性格不改规则，只是让你像个具体的牌手在想问题，" +
            "而不是个中立的逻辑机器。")
    }
}
